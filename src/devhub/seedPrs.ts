/** Build a hunk from ` ctx` / `+add` / `-del` lines, numbering both sides. */
export function hunk(id: string, oldStart: number, newStart: number, header: string, src: string[]): DiffHunk {
  let o = oldStart;
  let n = newStart;
  const lines = src.map((raw) => {
    const sign = raw[0];
    const text = raw.slice(1);
    if (sign === '+') return { kind: 'add' as const, text, newNo: n++ };
    if (sign === '-') return { kind: 'del' as const, text, oldNo: o++ };
    return { kind: 'ctx' as const, text, oldNo: o++, newNo: n++ };
  });
  const oldLen = lines.filter((l) => l.kind !== 'add').length;
  const newLen = lines.filter((l) => l.kind !== 'del').length;
  return { id, header: `@@ -${oldStart},${oldLen} +${newStart},${newLen} @@ ${header}`.trim(), lines };
}

const file = (path: string, lang: FileLang, status: DiffFile['status'], hunks: DiffHunk[]): DiffFile => ({ path, lang, status, hunks });
const added = (id: string, path: string, lang: FileLang, lines: string[]): DiffFile => file(path, lang, 'added', [hunk(id, 0, 1, '', lines.map((l) => `+${l}`))]);

