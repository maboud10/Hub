function periodOffset(now: number, deltaMonths: number): string {
  const d = new Date(now);
  d.setDate(1);
  d.setMonth(d.getMonth() + deltaMonths);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
}

