const DAY = 86_400_000;
const now = Date.now();

/** MM-DD string for a date `offset` days from today (keeps the celebrations widget lively). */
function mmdd(offsetDays: number) {
  const d = new Date(now + offsetDays * DAY);
  return `${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/** ISO start date that hits a work anniversary `offsetDays` from today, `years` ago. */
function anniversary(years: number, offsetDays: number) {
  const d = new Date(now + offsetDays * DAY);
  d.setFullYear(d.getFullYear() - years);
  return d.toISOString().slice(0, 10);
}

/** ISO date `days` ago (recent joiners stay recent; matches their HR Portal onboarding journey). */
function isoDaysAgo(days: number) {
  const d = new Date(now - days * DAY);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

