const DAY_MS = 86_400_000;
const HOUR_MS = 3_600_000;
const MIN_MS = 60_000;

/** ISO YYYY-MM-DD in the given site's wall-clock timezone. */
export function siteDay(site: SiteId, dayOffset = 0, now = Date.now()): string {
  const target = new Date(now + dayOffset * DAY_MS);
  try {
    const tz = SITE_BY_ID[site]?.timezone ?? 'Asia/Dubai';
    const parts = new Intl.DateTimeFormat('en-CA', {
      timeZone: tz,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).formatToParts(target);
    const y = parts.find((p) => p.type === 'year')?.value;
    const m = parts.find((p) => p.type === 'month')?.value;
    const d = parts.find((p) => p.type === 'day')?.value;
    if (y && m && d) return `${y}-${m}-${d}`;
  } catch {
    // Fallback to UTC slice
  }
  return target.toISOString().slice(0, 10);
}

/** Site-local decimal hour (e.g. 10.5 = 10:30). */
export function siteHour(site: SiteId, now = Date.now()): number {
  try {
    const tz = SITE_BY_ID[site]?.timezone ?? 'Asia/Dubai';
    const parts = new Intl.DateTimeFormat('en-GB', {
      timeZone: tz,
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }).formatToParts(new Date(now));
    const h = Number(parts.find((p) => p.type === 'hour')?.value ?? 10);
    const m = Number(parts.find((p) => p.type === 'minute')?.value ?? 0);
    if (Number.isFinite(h) && Number.isFinite(m)) return +(h + m / 60).toFixed(2);
  } catch {
    // Fallback
  }
  const d = new Date(now);
  return +(d.getHours() + d.getMinutes() / 60).toFixed(2);
}

export function isoDay(now = Date.now(), dayOffset = 0): string {
  return siteDay('dubai', dayOffset, now);
}

export function dateMapForOffset(dayOffset = 0, now = Date.now()): Record<SiteId, string> {
  return {
    dubai: siteDay('dubai', dayOffset, now),
    london: siteDay('london', dayOffset, now),
    singapore: siteDay('singapore', dayOffset, now),
    newyork: siteDay('newyork', dayOffset, now),
  };
}

