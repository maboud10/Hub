export function getTagMeta(tag: string): PresetTagMeta {
  const clean = tag.replace(/^#/, '').trim().toLowerCase();
  const found = PRESET_DEVICE_TAGS.find((t) => t.tag === clean);
  if (found) return found;
  return {
    tag: clean,
    label: `#${clean}`,
    color: '#38bdf8',
    description: 'Custom IT fleet asset tag.',
  };
}

